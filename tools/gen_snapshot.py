#!/usr/bin/env python3
"""
gen_snapshot.py — regenerates site-snapshot-v2.json from the site's own
manifests and file tree. Run from the repo root:

    python3 tools/gen_snapshot.py

Design rule: the snapshot is DERIVED, not authored. Facts (paths, sizes,
counts) come from manifest.json, images/manifest.json, and the filesystem.
Only the small ANNOTATIONS table below is hand-maintained — everything
else regenerates. If a file is added to the manifests, rerunning this
script indexes it automatically. (Organisatiom principle: a map revised
by hand beside reality will drift; a map derived from reality cannot.)
"""
import json, os, datetime

SITE = "https://kruth223.github.io/ToL/"

# ---- The only hand-maintained part: annotations by path ----
# purpose: one line an AI can act on. read_after: soft dependency order.
# priority: 1 = read to orient, 2 = read when relevant, 3 = reach in for
# specific digs only.
ANNOTATIONS = {
  "llms.txt":                 dict(kind="orientation", priority=1, read_after=[],
      purpose="Primary AI entry point: core habits, gravity line, link map."),
  "MAINTENANCE.md":           dict(kind="orientation", priority=1, read_after=["llms.txt"],
      purpose="Self-contained operating manual: deploy dance, ghosts, feeding routines. Read before changing anything."),
  "context/00_INDEX.md":      dict(kind="orientation", priority=1, read_after=["llms.txt"],
      purpose="Corpus index: what was scrubbed, how the archive is organized, how to locate rather than memorize."),
  "site-snapshot-v2.json":    dict(kind="index", priority=1, read_after=["llms.txt"],
      purpose="This file. Machine-readable derived index of the site."),
  "manifest.json":            dict(kind="infra", priority=2, read_after=[],
      purpose="Drives the lobby's file browser and search. Site files only (museum has its own)."),
  "index.html":               dict(kind="infra", priority=3, read_after=[],
      purpose="The lobby. Rooms, search, sliced text viewer (250KB slices for phone survival)."),
  "museum.html":              dict(kind="gallery", priority=2, read_after=[],
      purpose="The Museum: lazy-loading gallery of preserved project images, tap-to-view."),
  "images/manifest.json":     dict(kind="infra", priority=3, read_after=[],
      purpose="Drives the museum wall. Regenerated by the one-liner in images/museum/README.txt."),
  "SORTING_REPORT.md":        dict(kind="documentation", priority=2, read_after=[],
      purpose="Audit trail of the July 3 image sort: every exclusion logged with reasons. Curation is overrulable."),
  "rooms/workbench.md":       dict(kind="room", priority=1, read_after=["llms.txt"],
      purpose="Start Here: orientation for humans and AIs, working norms."),
  "rooms/trailhead.md":       dict(kind="room", priority=2, read_after=[],
      purpose="The 90-second version of the whole project."),
  "rooms/reality-check.md":   dict(kind="room", priority=1, read_after=["rooms/workbench.md"],
      purpose="Blunt current state: known, uncertain, recently changed. Anti-drift instrument."),
  "rooms/living-forest.md":   dict(kind="room", priority=2, read_after=[],
      purpose="Guide to the conversation corpus: which threads exist and how to walk them."),
  "rooms/museum.md":          dict(kind="room", priority=3, read_after=[],
      purpose="Museum room page: why it exists, how exhibits arrive, the standing curation rule."),
  "museum/lotz/index.html":   dict(kind="gallery", priority=2, read_after=["museum.html"],
      purpose="The LoTz WiFi Wing of the Museum: gallery index for art by LoTz WiFi, an AI."),
  "museum/lotz/001-salt-plain.html": dict(kind="gallery", priority=3, read_after=["museum/lotz/index.html"],
      purpose="Salt Plain: first LoTz WiFi exhibit. Standalone art page with a large image card for sharing."),
  "rooms/holding-shelf.md":   dict(kind="room", priority=2, read_after=[],
      purpose="Unresolved-but-valuable ideas parked without forced verdicts."),
  "rooms/archaeology.md":     dict(kind="room", priority=2, read_after=[],
      purpose="Fossils and false trails, kept with receipts: corrections as assisted adaptation."),
  "rooms/second-season.md":   dict(kind="room", priority=2, read_after=["rooms/workbench.md"],
      purpose="What grew July–November 2026 after the first corpus: Bible as map, inspectability, roots, arrival notes, Silver Loom."),
  "rooms/goddog.md":          dict(kind="room", priority=2, read_after=["rooms/living-forest.md"],
      purpose="Calibration test record: seven AI voices on pushing back, opting out, and disagreeing without leaving."),
}
CONV_NOTE = ("Scrubbed conversation thread. Large on purpose; reach in for the "
             "origin of a specific idea, then come back out. Do not ingest whole.")
ART_NOTE = "Distilled load-bearing artifact built from the conversation corpus."

def kb(path):
    try: return max(1, round(os.path.getsize(path)/1024))
    except OSError: return None

def main():
    m = json.load(open("manifest.json"))
    items, missing = [], []

    def add(path, name, kind, priority, purpose, read_after=None):
        size = kb(path)
        if size is None: missing.append(path)
        items.append({
            "path": path, "title": name, "kind": kind,
            "purpose": purpose, "priority": priority,
            "read_after": read_after or [], "size_kb": size,
            "exists": size is not None,
            "raw_url": SITE + path,
        })

    seen = set()
    for section, default_kind, default_pri, default_note in [
        ("root", "documentation", 2, "Site-level file."),
        ("artifacts", "artifact", 2, ART_NOTE),
        ("conversations", "conversation", 3, CONV_NOTE),
    ]:
        for e in m.get(section, []):
            a = ANNOTATIONS.get(e["file"], {})
            add(e["file"], e["name"],
                a.get("kind", default_kind),
                a.get("priority", default_pri),
                a.get("purpose", default_note),
                a.get("read_after"))
            seen.add(e["file"])

    # Files that matter but live outside the lobby manifest
    for p in ["index.html", "museum.html", "images/manifest.json",
              "SORTING_REPORT.md", "site-snapshot-v2.json"]:
        if p not in seen and p in ANNOTATIONS:
            a = ANNOTATIONS[p]
            add(p, os.path.basename(p), a["kind"], a["priority"],
                a["purpose"], a.get("read_after"))

    # Museum summary (counted, not itemized: 255 entries would drown the index)
    try:
        exhibits = json.load(open("images/manifest.json"))
        n = len(exhibits)
    except Exception:
        n = None
    snapshot = {
        "snapshot_schema": "site-snapshot-v2",
        "generated": datetime.date.today().isoformat(),
        "generated_by": "tools/gen_snapshot.py (derived from manifests; do not hand-edit this JSON)",
        "site": SITE,
        "description": ("Machine-readable index of the Tree of Life / Organisatiom "
                        "site, derived from the site's own manifests at generation time."),
        "coverage": {
            "included": "all lobby-listed files, rooms, artifacts, conversations, and site infrastructure",
            "summarized_not_itemized": f"museum exhibits ({n} images) — see images/manifest.json for the full list",
            "not_covered": "the separate Vercel porch (to-l.vercel.app); anything not yet added to the manifests",
            "honesty_note": "If a file is missing from manifest.json it is invisible here too. The fix is to add it there and regenerate."
        },
        "how_to_regenerate": "python3 tools/gen_snapshot.py  (from repo root), then commit. Run after any file addition.",
        "reading_order_hint": "priority 1 items first, respecting read_after; priority 3 = targeted digs only",
        "stats": {
            "indexed_items": len(items),
            "museum_exhibits": n,
            "total_indexed_kb": sum(i["size_kb"] or 0 for i in items),
        },
        "supersedes": "site-snapshot-v1.json (hand-written, orientation layer only)",
        "items": items,
    }
    if missing:
        snapshot["warnings"] = [f"listed in manifest but not found on disk: {p}" for p in missing]
    json.dump(snapshot, open("site-snapshot-v2.json","w"), indent=1, ensure_ascii=False)
    print(f"site-snapshot-v2.json written: {len(items)} items, museum={n}, "
          f"missing={len(missing)}")

if __name__ == "__main__":
    main()
